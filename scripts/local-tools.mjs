import { spawnSync } from "node:child_process";
import { lstat, readFile, rename, unlink, writeFile } from "node:fs/promises";
import * as nodeUtil from "node:util";
import { randomUUID } from "node:crypto";
import { join } from "node:path";
const parseEnv = nodeUtil.parseEnv;

export function supportedNode(version = process.versions.node) {
  const [major, minor] = version.split(".").map(Number);
  return (major === 22 && minor >= 18) || major === 24 || major >= 26;
}

export function run(command, args, options = {}) {
  const child = spawnSync(command, args, { stdio: "inherit", ...options });
  if (child.error || child.status !== 0) throw new Error("Command did not complete");
  return child;
}

export function packageCommand() {
  const executable = process.env.npm_execpath;
  if (!executable) throw new Error("Run this command through pnpm run (or npx pnpm@10.32.1 run).");
  return /\.[cm]?js$/i.test(executable)
    ? (args, options) => run(process.execPath, [executable, ...args], options)
    : (args, options) => run(executable, args, options);
}

export async function readSettings(root = process.cwd()) {
  const file = join(root, ".env");
  const stat = await lstat(file);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(".env must be a regular private file.");
  const env = parseEnv(await readFile(file, "utf8"));
  const port = Number(env.PORT ?? 3433);
  if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new Error("Check PORT in .env; use a number from 1024 to 65535.");
  if (!env.MCP_TOKEN || env.MCP_TOKEN.length < 32) throw new Error("Check MCP_TOKEN in private .env. local:init creates a missing file; it does not repair an existing configuration.");
  return { env, port, origin: `http://127.0.0.1:${port}` };
}

export function accessMode(env) {
  if (env.AMAZON_LIVE_ENABLED !== "true") return "offline";
  if (env.AMAZON_READ_ONLY === "false" && env.AMAZON_PURCHASING_ENABLED === "true") return "purchasing";
  return env.AMAZON_READ_ONLY === "false" ? "cart" : "read-only";
}

export async function setAccessMode(mode, root = process.cwd()) {
  if (!["offline", "read-only", "purchasing"].includes(mode)) throw new Error("Choose offline, read-only, or purchasing.");
  await readSettings(root);
  const file = join(root, ".env");
  const original = await readFile(file, "utf8");
  const changes = {
    AMAZON_LIVE_ENABLED: mode === "offline" ? "false" : "true",
    AMAZON_READ_ONLY: mode === "purchasing" ? "false" : "true",
    AMAZON_PURCHASING_ENABLED: mode === "purchasing" ? "true" : "false",
  };
  let updated = original;
  for (const [key, value] of Object.entries(changes)) {
    // Remove every definition so an earlier duplicate cannot restore another mode.
    updated = updated.replace(new RegExp(`^[\\t ]*(?:export[\\t ]+)?${key}[\\t ]*=.*(?:\\r?\\n|$)`, "gm"), "");
    updated = `${updated.trimEnd()}\n${key}=${value}\n`;
  }
  const before = parseEnv(original), after = parseEnv(updated);
  for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
    if (after[key] !== (changes[key] ?? before[key]))
      throw new Error("The access settings use an unsupported multiline format. Edit these three flags in .env manually; no file was changed.");
  }
  const temporary = `${file}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, updated, { mode: 0o600, flag: "wx" });
    await rename(temporary, file);
  } finally { await unlink(temporary).catch(() => undefined); }
}

export async function gatewayRunning(origin) {
  try {
    const response = await fetch(`${origin}/health`, { signal: AbortSignal.timeout(2000) });
    return response.ok && (await response.json()).status === "running";
  } catch { return false; }
}

